// Builds the Edit text sweep asset (src/ascii-sweep.js) from sweep/main.tsx and
// the Canvas UI component beside it. Run: npm run build:sweep
//
// The output is committed. The package ships plain files and has no build step
// at publish time, the same way src/edityy.js is shipped as it is written.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const at = (path) => fileURLToPath(new URL(path, root));

await build({
  entryPoints: [at("sweep/main.tsx")],
  outfile: at("src/ascii-sweep.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  // The browsers the launcher supports: optional chaining, class fields and the
  // rest are all older than this.
  target: "es2020",
  jsx: "automatic",
  minify: true,
  // React reads this once, at import. Defined rather than left to the bundler,
  // so the asset has no reference to a `process` the page may not have.
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  banner: { js: "/* Generated by npm run build:sweep from sweep/. Do not edit. */" },
});
